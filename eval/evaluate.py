"""Evaluate retrieval quality of the lexical, semantic and hybrid modes.

Reads ``eval/queries.jsonl`` (``{"query": ..., "relevant": [doc_ids]}`` per
line), runs every query in each mode and reports the average of:

* **Precision@k**: relevant documents in the top ``k`` divided by ``k``. The
  divisor is always ``k``, even when fewer than ``k`` documents are relevant,
  so the best possible value for a query is ``min(k, #relevant) / k``.
* **Recall@k**: relevant documents in the top ``k`` divided by the number of
  relevant documents.
* **MRR**: mean reciprocal rank of the first relevant hit within the top ``k``
  (0 when none of the top ``k`` is relevant).

Labels generated by ``make_queries.py`` are literal phrase matches and
therefore favour lexical mode; see that module's docstring.

Usage:  python eval/evaluate.py [--k 10] [--verbose] [--queries PATH]
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Collection, Sequence
from pathlib import Path
from typing import TYPE_CHECKING, Final, NamedTuple

if TYPE_CHECKING:  # heavy imports (torch, faiss) only when actually evaluating
    from search_engine.hybrid_engine import HybridEngine

BASE_DIR: Final[Path] = Path(__file__).resolve().parent.parent
QUERIES_PATH: Final[Path] = BASE_DIR / "eval" / "queries.jsonl"
DEFAULT_K: Final[int] = 10
MODES: Final[tuple[str, ...]] = ("lexical", "semantic", "hybrid")


class Query(NamedTuple):
    """One labelled evaluation query.

    Attributes:
        text: The query string sent to the engine.
        relevant: Identifiers of the documents judged relevant.
    """

    text: str
    relevant: frozenset[str]


class QueryScore(NamedTuple):
    """Metrics for one query in one mode.

    Attributes:
        query: The query string.
        precision: Precision@k.
        recall: Recall@k.
        reciprocal_rank: Reciprocal rank of the first relevant hit (0 if none).
    """

    query: str
    precision: float
    recall: float
    reciprocal_rank: float


def _top_k(ranked: Sequence[str], k: int) -> list[str]:
    """Return the first ``k`` distinct identifiers of a ranking.

    Args:
        ranked: Document identifiers, best first.
        k: Cut-off rank.

    Returns:
        At most ``k`` identifiers, duplicates removed.

    Raises:
        ValueError: If ``k`` is not positive.
    """
    if k <= 0:
        raise ValueError("k must be positive.")
    return list(dict.fromkeys(ranked))[:k]


def precision_at_k(ranked: Sequence[str], relevant: Collection[str], k: int) -> float:
    """Compute Precision@k (always divided by ``k``).

    Args:
        ranked: Document identifiers, best first.
        relevant: Identifiers judged relevant.
        k: Cut-off rank.

    Returns:
        Relevant hits in the top ``k`` divided by ``k``.
    """
    relevant_set = set(relevant)
    hits = sum(1 for doc_id in _top_k(ranked, k) if doc_id in relevant_set)
    return hits / k


def recall_at_k(ranked: Sequence[str], relevant: Collection[str], k: int) -> float:
    """Compute Recall@k.

    Args:
        ranked: Document identifiers, best first.
        relevant: Identifiers judged relevant.
        k: Cut-off rank.

    Returns:
        Relevant hits in the top ``k`` divided by the number of relevant
        documents; ``0.0`` when there are no relevant documents.
    """
    relevant_set = set(relevant)
    if not relevant_set:
        return 0.0
    hits = sum(1 for doc_id in _top_k(ranked, k) if doc_id in relevant_set)
    return hits / len(relevant_set)


def reciprocal_rank(ranked: Sequence[str], relevant: Collection[str], k: int) -> float:
    """Compute the reciprocal rank of the first relevant hit within the top ``k``.

    Args:
        ranked: Document identifiers, best first.
        relevant: Identifiers judged relevant.
        k: Cut-off rank.

    Returns:
        ``1 / rank`` of the first relevant document, or ``0.0`` if there is none.
    """
    relevant_set = set(relevant)
    for rank, doc_id in enumerate(_top_k(ranked, k), start=1):
        if doc_id in relevant_set:
            return 1.0 / rank
    return 0.0


def load_queries(path: Path) -> list[Query]:
    """Read labelled queries from a JSONL file.

    Args:
        path: File with one ``{"query": str, "relevant": [str, ...]}`` per line.

    Returns:
        The queries in file order.

    Raises:
        ValueError: If a line is invalid JSON, or has an empty query or an
            empty/non-string ``relevant`` list.
    """
    queries: list[Query] = []
    with path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"{path}:{line_number}: invalid JSON ({exc})") from exc
            relevant = record.get("relevant") if isinstance(record, dict) else None
            text = record.get("query") if isinstance(record, dict) else None
            if (
                not isinstance(text, str)
                or not text.strip()
                or not isinstance(relevant, list)
                or not relevant
                or not all(isinstance(doc_id, str) for doc_id in relevant)
            ):
                raise ValueError(
                    f"{path}:{line_number}: expected a non-empty string 'query' and a "
                    "non-empty list of string 'relevant' ids"
                )
            queries.append(Query(text, frozenset(relevant)))
    return queries


def score_mode(
    engine: HybridEngine, queries: Sequence[Query], mode: str, k: int
) -> list[QueryScore]:
    """Run every query in one retrieval mode and score the rankings.

    Args:
        engine: The loaded hybrid engine.
        queries: Labelled queries.
        mode: ``"lexical"``, ``"semantic"`` or ``"hybrid"``.
        k: Cut-off rank (also the number of results requested).

    Returns:
        One :class:`QueryScore` per query, in input order.
    """
    scores: list[QueryScore] = []
    for query in queries:
        ranked = [hit.doc_id for hit in engine.search(query.text, top_k=k, mode=mode)]
        scores.append(
            QueryScore(
                query.text,
                precision_at_k(ranked, query.relevant, k),
                recall_at_k(ranked, query.relevant, k),
                reciprocal_rank(ranked, query.relevant, k),
            )
        )
    return scores


def mean(values: Sequence[float]) -> float:
    """Average a sequence of numbers.

    Args:
        values: The numbers to average.

    Returns:
        The arithmetic mean, or ``0.0`` for an empty sequence.
    """
    return sum(values) / len(values) if values else 0.0


def _positive_int(value: str) -> int:
    """Parse a strictly positive integer for argparse.

    Args:
        value: The raw command-line string.

    Returns:
        The parsed integer.

    Raises:
        argparse.ArgumentTypeError: If ``value`` is not an integer >= 1.
    """
    try:
        number = int(value)
    except ValueError:
        raise argparse.ArgumentTypeError(f"{value!r} is not an integer") from None
    if number < 1:
        raise argparse.ArgumentTypeError("must be >= 1")
    return number


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments.

    Args:
        argv: Argument list; defaults to ``sys.argv[1:]``.

    Returns:
        The parsed namespace.
    """
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--queries", type=Path, default=QUERIES_PATH, help="Queries JSONL.")
    parser.add_argument(
        "--k", type=_positive_int, default=DEFAULT_K, help="Cut-off rank (default: 10)."
    )
    parser.add_argument(
        "--verbose", action="store_true", help="Also print the scores of every query."
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> None:
    """Evaluate all modes and print Precision@k, Recall@k and MRR.

    Args:
        argv: Argument list; defaults to ``sys.argv[1:]``.
    """
    args = parse_args(argv)
    if not args.queries.is_file():
        raise SystemExit(
            f"{args.queries} not found. Run `python eval/make_queries.py` or write it by hand."
        )
    queries = load_queries(args.queries)
    if not queries:
        raise SystemExit(f"{args.queries} contains no queries.")

    if str(BASE_DIR) not in sys.path:
        sys.path.insert(0, str(BASE_DIR))
    from preflight import ensure_indexes
    from search_engine.hybrid_engine import HybridEngine

    try:
        ensure_indexes(auto=False)
    except RuntimeError as exc:
        raise SystemExit(str(exc)) from exc

    engine = HybridEngine.load_from_disk(
        BASE_DIR / "data" / "tantivy_index", BASE_DIR / "data" / "vector_index"
    )
    k = args.k
    try:
        engine.warmup()
        results = {mode: score_mode(engine, queries, mode, k) for mode in MODES}
    finally:
        engine.close()

    if args.verbose:
        for mode, scores in results.items():
            print(f"\n[{mode}] per-query scores (k={k})")
            for score in scores:
                print(
                    f"  {score.query[:48]:<48}  P@{k}={score.precision:.3f}  "
                    f"R@{k}={score.recall:.3f}  RR={score.reciprocal_rank:.3f}"
                )

    print(f"\nQueries: {len(queries)}   k: {k}")
    print(f"{'mode':<10} {f'P@{k}':>8} {f'Recall@{k}':>10} {'MRR':>8}")
    for mode, scores in results.items():
        print(
            f"{mode:<10} {mean([s.precision for s in scores]):>8.3f} "
            f"{mean([s.recall for s in scores]):>10.3f} "
            f"{mean([s.reciprocal_rank for s in scores]):>8.3f}"
        )


if __name__ == "__main__":
    main()